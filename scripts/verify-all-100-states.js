const resolveState = (addr) => {
  const up = addr.toUpperCase();
  const pinMatch = up.match(/(?<![0-9])(\d{6})(?![0-9])/);
  if (pinMatch) {
    const pin = parseInt(pinMatch[1], 10);
    const s = deriveStateFromPin(pin);
    if (s) return { state: s, method: `pin ${pinMatch[1]}` };
  }
  return { state: '❌ NOT DERIVED', method: 'none' };
};

